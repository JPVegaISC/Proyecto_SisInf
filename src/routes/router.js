const express = require('express')
const router = express.Router()
const auth = require('../middleware/auth')
const { verifyCsrf } = require('../middleware/csrf')
const login = require('../controllers/authController')
const dashboard = require('../controllers/dashboardController')
const usuarios = require('../controllers/managementController')
const expedientes = require('../controllers/expedientesController')
const grupos = require('../controllers/gruposController')
const recepcion = require('../controllers/recepcionController')
const cuidados = require('../controllers/cuidadosController')
const insumos = require('../controllers/insumosController')
const salidas = require('../controllers/salidasController')
const movimientos = require('../controllers/movimientosController')

router.get('/login', (req, res) => req.usuario ? res.redirect('/') : login.loginView(req, res))
router.post('/login', verifyCsrf, login.loginWeb)
router.post('/logout', auth.requireWebAuth, verifyCsrf, login.logoutWeb)
router.get('/configuracion', auth.requireWebAuth, login.settingsView)
router.get('/configuracion/acceso', auth.requireWebAuth, login.tokenView)
// La URL anterior permanece para no romper marcadores guardados.
router.get('/mi-token', auth.requireWebAuth, (req, res) => res.redirect('/configuracion/acceso'))
router.get('/', auth.requireWebAuth, dashboard.show)
router.get('/usuarios', auth.requireWebAuth, auth.requireRole('administrador'), usuarios.list)
router.get('/usuarios/nuevo', auth.requireWebAuth, auth.requireRole('administrador'), usuarios.newForm)
router.post('/usuarios/nuevo', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, usuarios.create)
router.get('/usuarios/:id/editar', auth.requireWebAuth, auth.requireRole('administrador'), usuarios.editForm)
router.post('/usuarios/:id/editar', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, usuarios.update)
router.post('/usuarios/:id/estado', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, usuarios.toggleActive)

// Administración organiza los grupos; los encargados consultan los asignados.
router.get('/grupos', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), grupos.list)
router.post('/grupos/nuevo', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, grupos.crearGrupo)
router.post('/grupos/:id/desactivar', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, grupos.desactivarGrupo)
router.get('/grupos/menores/:id/cambiar', auth.requireWebAuth, auth.requireRole('administrador'), grupos.cambioForm)
router.post('/grupos/menores/:id/cambiar', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, grupos.cambiarGrupo)
router.get('/grupos/:id', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), grupos.show)
router.post('/grupos/:id/encargado', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, grupos.asignarEncargado)
router.get('/recepcion', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), recepcion.list)
router.post('/recepcion/horario', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, recepcion.actualizarHorario)
router.get('/recepcion/:id', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), recepcion.form)
router.post('/recepcion/:id', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), verifyCsrf, recepcion.registrar)

// Salidas, avisos y movimientos del expediente.
router.get('/salidas', auth.requireWebAuth, auth.requireRole('administrador'), salidas.list)
router.get('/salidas/:id', auth.requireWebAuth, auth.requireRole('administrador'), salidas.form)
router.post('/salidas/:id/aviso', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, salidas.avisar)
router.post('/salidas/:id', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, salidas.registrar)
router.post('/expedientes/:id/estado', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, movimientos.cambiarEstado)

// Cuidados diarios y control de insumos.
router.get('/cuidados', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), cuidados.list)
router.get('/cuidados/:id', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), cuidados.show)
router.post('/cuidados/:id', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), verifyCsrf, cuidados.registrar)
router.get('/insumos', auth.requireWebAuth, auth.requireRole('administrador', 'encargado'), insumos.list)
router.post('/insumos', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, insumos.crear)
router.post('/insumos/:id', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, insumos.actualizar)

// El administrador registra y modifica. El resto del personal solo consulta.
router.get('/expedientes', auth.requireWebAuth, expedientes.list)
router.get('/expedientes/nuevo', auth.requireWebAuth, auth.requireRole('administrador'), expedientes.newForm)
router.post('/expedientes/nuevo', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, expedientes.create)
router.get('/expedientes/:id', auth.requireWebAuth, expedientes.show)
router.get('/expedientes/:id/editar', auth.requireWebAuth, auth.requireRole('administrador'), expedientes.editForm)
router.post('/expedientes/:id/editar', auth.requireWebAuth, auth.requireRole('administrador'), verifyCsrf, expedientes.update)
router.post('/api/auth/login', login.apiLogin)
router.get('/api/auth/me', auth.requireBearer, login.apiMe)
router.get('/api/usuarios', auth.requireBearer, auth.requireApiRole('administrador'), usuarios.apiList)
router.get('/api/expedientes', auth.requireBearer, auth.requireApiRole('administrador', 'encargado', 'enfermeria'), expedientes.apiList)
router.get('/api/expedientes/:id', auth.requireBearer, auth.requireApiRole('administrador', 'encargado', 'enfermeria'), expedientes.apiShow)
module.exports = router
